#!/usr/bin/env python3
"""Before and after screenshots of an autopilot pull request (#564 C4).

When an autopilot pull request that touches the browser layer is marked
ready (pr-screenshots.yml), the specs that cover what it changed run on its
base and on its head with a screenshot of every test, and its "📸
Screenshots" section links both, side by side. Nothing here is a new list:
"the browser layer" and "the specs it affects" are the repository's pack and
policy (scripts/repro-ways.py): the way whose layer is `browser`, and the
tests `repro.affected` maps the changed paths to, kept when they are that
way's specs (its `example` glob, `*.spec.ts` under the e2e tests). None:
nothing runs. The repository's own Playwright configuration is never
changed: a generated `playwright.dx-shots.config.ts` imports it and turns
`screenshot` on. The images live on the repository's orphan branch
`dx-screenshots`, `pr-<n>/{before,after}/<spec>/<test>.png`, so whoever can
see the pull request sees them, a private repository's included. The
section is rewritten between its markers, so a later run replaces it; a run
that fails says so there and blocks nothing.

  screenshots.py plan       the changed paths on stdin, the repository at
                            ROOT (default .), DiluxOne/.github at CENTRAL:
                            JSON {"specs", "setup", "teardown", "config"} and
                            to $GITHUB_OUTPUT `run` (true|false) and `plan`
  screenshots.py config BASE  the generated configuration, importing BASE
  screenshots.py collect REPORT SIDE OUT   the screenshots of Playwright's
                            JSON report REPORT, copied to OUT/SIDE/<spec>/<test>.png;
                            prints the manifest, {spec: {test: path}}
  screenshots.py section    the section, from OUT (before/, after/ and their
                            manifests) for REPOSITORY, PR and the commit
                            SHOTS_SHA of the branch; FAILED="why" says the
                            run failed instead
  screenshots.py apply BODY SECTION   the pull request's body with its
                            "📸 Screenshots" section replaced
  screenshots.py publish OUT   OUT's images committed to `dx-screenshots`
                            through the API (GH_TOKEN, GITHUB_REPOSITORY, PR);
                            prints the commit
  screenshots.py --test     self-test
"""
import base64
import importlib.util
import json
import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BRANCH = "dx-screenshots"
CONFIG = "playwright.dx-shots.config.ts"
START, END = "<!-- dx-screenshots -->", "<!-- /dx-screenshots -->"
HEADING = "## 📸 Screenshots"
SIGN = "<sub>🤖 Screenshots (scripts/screenshots.py)</sub>"
SIDES = ("before", "after")


def ways():
    spec = importlib.util.spec_from_file_location("repro_ways", os.path.join(HERE, "repro-ways.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def browser_way(conf):
    """(name, way) of the repository's browser way, or (None, None)."""
    rw = ways()
    for name, way in conf["ways"].items():
        if "browser" in rw.layers(way):
            return name, way
    return None, None


def plan(conf, kind, paths, root=".", central=".dx-central"):
    """The specs a pull request's changed PATHS affect in the browser layer,
    and how to run them (the browser way's setup and teardown). Pure but for
    reading which specs exist under ROOT."""
    rw = ways()
    name, way = browser_way(conf)
    out = {"specs": [], "setup": [], "teardown": "", "config": "playwright.config.ts"}
    if not way:
        return out
    glob = str(way.get("example") or "**/*.spec.ts")
    hit = rw.affected(conf, paths, root)
    specs = [t for t in hit["tests"] + hit["repro"] if rw.glob_match(t, glob) and os.path.isfile(os.path.join(root, t))]
    base = next((str(n) for n in way.get("needs") or [] if re.fullmatch(r"playwright\.config\.[cm]?[jt]s", str(n))), "playwright.config.ts")
    out.update({"specs": sorted(set(specs)), "config": base,
                "setup": [rw.fill(s, 0, central, kind) for s in (way.get("setup") or [])],
                "teardown": rw.fill(way.get("teardown") or "", 0, central, kind)})
    return out


def config(base):
    """The generated configuration: the repository's own, with a screenshot
    of every test and a JSON report, no retries. Pure."""
    mod = "./" + re.sub(r"\.[cm]?[jt]s$", "", os.path.basename(base))
    return f"""// Generated by DiluxOne/.github scripts/screenshots.py (#564): the repository's
// own configuration, with a screenshot of every test. Never committed.
import base from '{mod}';
import {{ defineConfig }} from '@playwright/test';

const out = process.env.DX_SHOTS_DIR || 'build/dx-shots';

export default defineConfig({{
  ...base,
  retries: 0,
  outputDir: out + '/results',
  reporter: [['json', {{ outputFile: out + '/report.json' }}]],
  use: {{ ...(base.use || {{}}), screenshot: 'on' }},
}});
"""


def slug(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:80] or "test"


def shots(report):
    """[(spec file, test title, png path)] of a Playwright JSON report. Pure."""
    found = []

    def walk(suite, titles):
        for spec in suite.get("specs") or []:
            title = " › ".join([*titles, spec.get("title") or ""]).strip(" ›")
            for test in spec.get("tests") or []:
                for result in (test.get("results") or [])[-1:]:
                    for a in result.get("attachments") or []:
                        if a.get("contentType") == "image/png" and a.get("path"):
                            found.append((spec.get("file") or suite.get("file") or "", title, a["path"]))
        for child in suite.get("suites") or []:
            walk(child, [*titles, child.get("title") or ""] if child.get("title") and child.get("title") != child.get("file") else titles)

    for s in report.get("suites") or []:
        walk(s, [])
    return found


def collect(report_path, side, out):
    manifest = {}
    with open(report_path, encoding="utf-8") as fh:
        report = json.load(fh)
    for spec, title, png in shots(report):
        if not os.path.isfile(png):
            continue
        rel = f"{side}/{slug(os.path.basename(spec))}/{slug(title)}.png"
        os.makedirs(os.path.dirname(os.path.join(out, rel)), exist_ok=True)
        shutil.copyfile(png, os.path.join(out, rel))
        manifest.setdefault(spec, {})[title] = rel
    with open(os.path.join(out, f"{side}.json"), "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=1)
    return manifest


def section(repository, pr, sha, before, after, failed=""):
    """The "📸 Screenshots" section between its markers: a table of every
    test, its image before and after, linked at the branch's commit. Pure."""
    lines = [START]
    if failed:
        lines += [f"The screenshots could not be taken ({failed}). This blocks nothing; a person may attach them by hand.", "", SIGN, END]
        return "\n".join(lines)
    url = lambda rel: f"https://github.com/{repository}/blob/{sha}/pr-{pr}/{rel}?raw=true"
    rows = []
    for spec in sorted(set(before) | set(after)):
        for test in sorted(set(before.get(spec) or {}) | set(after.get(spec) or {})):
            cell = lambda m, side: f"![{side}]({url(m[spec][test])})" if test in (m.get(spec) or {}) else "none"
            rows.append(f"| `{spec}` · {test.replace('|', '/')} | {cell(before, 'before')} | {cell(after, 'after')} |")
    if not rows:
        lines += ["The specs this pull request affects in the browser layer ran, and took no screenshot.", "", SIGN, END]
        return "\n".join(lines)
    lines += [f"Before (its base) and after (its head), for the specs it affects in the browser layer, from the `{BRANCH}` branch.", "",
              "| Spec · test | Before | After |", "| --- | --- | --- |", *rows, "", SIGN, END]
    return "\n".join(lines)


def apply(body, text):
    """The body with its screenshots section replaced: between the markers
    when there, else under the "📸 Screenshots" heading (until the next
    heading), else added at the end. Pure."""
    body = body or ""
    if START in body and END in body:
        a, b = body.index(START), body.index(END) + len(END)
        return body[:a] + text + body[b:]
    m = re.search(r"^## 📸 Screenshots[^\n]*\n", body, re.M)
    if m:
        nxt = re.search(r"^## ", body[m.end():], re.M)
        end = m.end() + (nxt.start() if nxt else len(body) - m.end())
        return body[:m.end()] + "\n" + text + "\n\n" + body[end:].lstrip("\n")
    return body.rstrip("\n") + f"\n\n{HEADING}\n\n{text}\n"


def gh(*args, data=None):
    res = subprocess.run(["gh", "api", *args] + (["--input", "-"] if data is not None else []),
                         input=json.dumps(data) if data is not None else None, capture_output=True, text=True)
    if res.returncode != 0:
        raise RuntimeError(res.stderr.strip()[:300])
    return json.loads(res.stdout) if res.stdout.strip() else {}


def publish(repo, pr, out):
    """OUT's images, committed on the orphan branch through the API (a
    commit GitHub signs), under pr-<n>/, replacing that pull request's last."""
    files = []
    for side in SIDES:
        for dirpath, _, names in os.walk(os.path.join(out, side)):
            for n in names:
                if n.endswith(".png"):
                    path = os.path.join(dirpath, n)
                    files.append((f"pr-{pr}/{os.path.relpath(path, out)}", path))
    try:
        head = gh(f"repos/{repo}/git/ref/heads/{BRANCH}")["object"]["sha"]
        base_tree = gh(f"repos/{repo}/git/commits/{head}")["tree"]["sha"]
    except RuntimeError as err:
        if "404" not in str(err) and "Not Found" not in str(err):
            raise
        head, base_tree = None, None
    tree = [{"path": f"pr-{pr}", "mode": "040000", "type": "tree", "sha": None}] if base_tree else []
    for path, local in sorted(files):
        blob = gh("-X", "POST", f"repos/{repo}/git/blobs", data={"content": base64.b64encode(open(local, "rb").read()).decode(), "encoding": "base64"})
        tree.append({"path": path, "mode": "100644", "type": "blob", "sha": blob["sha"]})
    if base_tree:
        # The pull request's last images go, then its new ones come.
        base_tree = gh("-X", "POST", f"repos/{repo}/git/trees", data={"base_tree": base_tree, "tree": tree[:1]})["sha"]
        tree = tree[1:]
    made = gh("-X", "POST", f"repos/{repo}/git/trees", data={**({"base_tree": base_tree} if base_tree else {}), "tree": tree})["sha"]
    commit = gh("-X", "POST", f"repos/{repo}/git/commits", data={"message": f"Screenshots of #{pr}", "tree": made, "parents": [head] if head else []})["sha"]
    if head:
        gh("-X", "PATCH", f"repos/{repo}/git/refs/heads/{BRANCH}", data={"sha": commit})
    else:
        gh("-X", "POST", f"repos/{repo}/git/refs", data={"ref": f"refs/heads/{BRANCH}", "sha": commit})
    return commit


def emit(pairs):
    if os.environ.get("GITHUB_OUTPUT"):
        with open(os.environ["GITHUB_OUTPUT"], "a", encoding="utf-8") as fh:
            for k, v in pairs.items():
                fh.write(f"{k}={v}\n")


def self_test():
    import tempfile
    fails = []

    def check(name, got, want):
        print(("ok   " if got == want else "FAIL ") + name + ("" if got == want else f": got {got!r}, want {want!r}"))
        if got != want:
            fails.append(name)

    rw = ways()
    with tempfile.TemporaryDirectory() as d:
        for f in ("tests/e2e/specs/layout.spec.ts", "tests/e2e/specs/admin.spec.ts", "tests/e2e/repro/issue-12.spec.ts", "tests/Unit/FooTest.php"):
            os.makedirs(os.path.dirname(os.path.join(d, f)), exist_ok=True)
            open(os.path.join(d, f), "w").close()
        pack = rw.read(os.path.join(HERE, "..", "kinds", "wordpress-plugin", "pack.yml"))
        repo = {"repro": {"affected": [{"paths": ["assets/**/*.css", "templates/**"], "tests": ["tests/e2e/specs/layout.spec.ts"]},
                                       {"paths": ["includes/**"], "tests": ["tests/Unit/FooTest.php"]}]}}
        conf = rw.merged(pack, repo)
        p = plan(conf, "wordpress-plugin", ["assets/css/front.css"], d)
        check("C4 a browser-layer path gives the specs that cover it", p["specs"], ["tests/e2e/specs/layout.spec.ts"])
        check("C4 with the browser way's setup, from the pack", ("npm ci --no-audit --no-fund" in p["setup"], any("npx wp-env start" == s for s in p["setup"]), p["teardown"]), (True, True, "npx wp-env stop"))
        check("C4 the {kind} of the setup is the pack's directory", any(".dx-central/kinds/wordpress-plugin/" in s for s in p["setup"]), True)
        check("C4 a path only a unit test covers: nothing runs", plan(conf, "wordpress-plugin", ["includes/a.php"], d)["specs"], [])
        check("C4 a reproduction spec it carries is one of them", plan(conf, "wordpress-plugin", ["assets/css/front.css", "tests/e2e/repro/issue-12.spec.ts"], d)["specs"],
              ["tests/e2e/repro/issue-12.spec.ts", "tests/e2e/specs/layout.spec.ts"])
        check("C4 a docs-only change: nothing runs", plan(conf, "wordpress-plugin", ["readme.txt"], d)["specs"], [])
        check("C4 a repository with no browser way: nothing runs", plan(rw.merged(pack, {"repro": {"ways": {"browser": False}, **repo["repro"]}}), "wordpress-plugin", ["assets/css/front.css"], d)["specs"], [])
        check("C4 its base configuration is the browser way's", p["config"], "playwright.config.ts")
    cfg = config("playwright.config.ts")
    check("C4 the generated config imports the repository's own", "import base from './playwright.config';" in cfg, True)
    check("C4 and takes a screenshot of every test", ("screenshot: 'on'" in cfg, "...(base.use || {})" in cfg, "...base," in cfg), (True, True, True))
    check("C4 with a JSON report and no retries", ("['json', { outputFile: out + '/report.json' }]" in cfg, "retries: 0" in cfg), (True, True))
    report = {"suites": [{"title": "layout.spec.ts", "file": "specs/layout.spec.ts", "specs": [], "suites": [
        {"title": "the header", "file": "specs/layout.spec.ts", "specs": [
            {"title": "stays on one line", "file": "specs/layout.spec.ts", "tests": [{"results": [
                {"attachments": [{"name": "screenshot", "contentType": "image/png", "path": "/tmp/x/test-finished-1.png"}, {"name": "trace", "contentType": "application/zip", "path": "t.zip"}]}]}]}]}]}]}
    check("C4 a report's screenshots, by spec and test", shots(report), [("specs/layout.spec.ts", "the header › stays on one line", "/tmp/x/test-finished-1.png")])
    with tempfile.TemporaryDirectory() as d:
        png = os.path.join(d, "a.png")
        open(png, "wb").write(b"\x89PNG")
        report["suites"][0]["suites"][0]["specs"][0]["tests"][0]["results"][0]["attachments"][0]["path"] = png
        json.dump(report, open(os.path.join(d, "report.json"), "w"))
        m = collect(os.path.join(d, "report.json"), "before", os.path.join(d, "out"))
        check("C4 collect copies them where the section links them", (m, os.path.isfile(os.path.join(d, "out", "before", "layout-spec-ts", "the-header-stays-on-one-line.png"))),
              ({"specs/layout.spec.ts": {"the header › stays on one line": "before/layout-spec-ts/the-header-stays-on-one-line.png"}}, True))
    before = {"specs/layout.spec.ts": {"stays on one line": "before/layout-spec-ts/stays-on-one-line.png"}}
    after = {"specs/layout.spec.ts": {"stays on one line": "after/layout-spec-ts/stays-on-one-line.png", "a new test": "after/layout-spec-ts/a-new-test.png"}}
    sec = section("DiluxOne/diluxone-fm", 283, "abc123", before, after)
    check("C4 the section links the before and the after image of each test",
          "| `specs/layout.spec.ts` · stays on one line | ![before](https://github.com/DiluxOne/diluxone-fm/blob/abc123/pr-283/before/layout-spec-ts/stays-on-one-line.png?raw=true) | "
          "![after](https://github.com/DiluxOne/diluxone-fm/blob/abc123/pr-283/after/layout-spec-ts/stays-on-one-line.png?raw=true) |" in sec, True)
    check("C4 a test with no before says so", "| `specs/layout.spec.ts` · a new test | none | ![after]" in sec, True)
    check("C4 between its markers", (sec.startswith(START), sec.endswith(END)), (True, True))
    check("C4 a failed run says so, and blocks nothing", "could not be taken (the site did not start). This blocks nothing" in section("o/r", 1, "", {}, {}, failed="the site did not start"), True)
    tpl = open(os.path.join(HERE, "..", "pull_request_template.md"), encoding="utf-8").read()
    body = apply(tpl, sec)
    check("C4 the template's section is filled, the next one kept", (sec in body, body.count(HEADING), "## ✅ Checklist" in body, body.index(sec) < body.index("## ✅ Checklist")), (True, 1, True, True))
    again = apply(body, section("o/r", 1, "", {}, {}, failed="x"))
    check("C4 a later run replaces it, never adds one", (again.count(START), sec in again, "could not be taken (x)" in again), (1, False, True))
    check("C4 a body with no section gets one at its end", apply("Closes #1.", sec), f"Closes #1.\n\n{HEADING}\n\n{sec}\n")
    print("all tests passed" if not fails else f"{len(fails)} failed")
    return 1 if fails else 0


def main(argv):
    if argv == ["--test"]:
        return self_test()
    if argv[:1] == ["plan"]:
        rw = ways()
        root, central = os.environ.get("ROOT", "."), os.environ.get("CENTRAL", ".dx-central")
        kind, conf = rw.config(root, central)
        paths = [l.strip() for l in sys.stdin if l.strip()]
        p = plan(conf, kind or "", paths, root, central)
        print(json.dumps(p))
        emit({"run": "true" if p["specs"] else "false", "plan": json.dumps(p, separators=(",", ":"))})
        return 0
    if argv[:1] == ["config"] and len(argv) == 2:
        sys.stdout.write(config(argv[1]))
        return 0
    if argv[:1] == ["collect"] and len(argv) == 4:
        print(json.dumps(collect(argv[1], argv[2], argv[3])))
        return 0
    if argv == ["section"]:
        out = os.environ.get("OUT", "")
        load = lambda side: json.load(open(os.path.join(out, f"{side}.json"), encoding="utf-8")) if out and os.path.isfile(os.path.join(out, f"{side}.json")) else {}
        print(section(os.environ["REPOSITORY"], os.environ["PR"], os.environ.get("SHOTS_SHA", BRANCH), load("before"), load("after"), os.environ.get("FAILED", "")))
        return 0
    if argv[:1] == ["apply"] and len(argv) == 3:
        sys.stdout.write(apply(open(argv[1], encoding="utf-8").read(), open(argv[2], encoding="utf-8").read().strip()))
        return 0
    if argv[:1] == ["publish"] and len(argv) == 2:
        print(publish(os.environ["GITHUB_REPOSITORY"], os.environ["PR"], argv[1]))
        return 0
    print(__doc__, file=sys.stderr)
    return 64


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
